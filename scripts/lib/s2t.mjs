const MAP = new Map();
for (const pair of PAIRS) if (pair[0] !== pair[1]) MAP.set(pair[0], pair[1]);

/** 零寬字元：從別處貼過來的內容常夾帶，看不見但會進字型子集 */
const INVISIBLE = /[​‌‍⁠﻿]/g;

export function toTraditional(text) {
  const changed = new Map();
  let out = text.replace(INVISIBLE, '');
  const strippedInvisible = text.length - out.length;
  out = [...out].map((ch) => {
    const t = MAP.get(ch);
    if (!t) return ch;
    changed.set(ch, (changed.get(ch) ?? 0) + 1);
    return t;
  }).join('');
  return { text: out, changed, strippedInvisible };
}
